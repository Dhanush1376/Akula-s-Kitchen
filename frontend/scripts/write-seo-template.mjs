// Bundles the built index.html into the SEO render function so it never has
// to read the filesystem or fetch itself at request time.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(root, 'dist', 'index.html'), 'utf8');
if (!html.includes('<!--seo:head-->')) {
  throw new Error('dist/index.html is missing the <!--seo:head--> marker');
}
const out = path.join(root, 'api', '_lib', 'template.generated.js');
fs.writeFileSync(out, `// Generated by scripts/write-seo-template.mjs. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`[seo] wrote ${path.relative(root, out)} (${html.length} bytes)`);
